#!/usr/bin/env node
/**
 * Regenerates art/prompts/NN-<category>.md from art/prompts.json.
 *
 * prompts.json is the source of truth. Edit it, run `node art/build-prompt-packs.js`,
 * and the paste-ready batch files rebuild. Never hand-edit the generated .md files —
 * they carry a "generated" banner and will be overwritten.
 *
 *   node art/build-prompt-packs.js
 */
const fs = require('fs');
const path = require('path');

const ROOT = __dirname;
const spec = JSON.parse(fs.readFileSync(path.join(ROOT, 'prompts.json'), 'utf8'));
const outDir = path.join(ROOT, 'prompts');
fs.mkdirSync(outDir, { recursive: true });

const STYLE_REF = `> **Before you paste this:** open \`00-style.md\`, copy the ACTIVE STYLE BLOCK, and paste it
> once at the top of a fresh ChatGPT conversation. Then paste this whole file as the next
> message. Attach \`../anchor-sheet.png\` to the message if you have it.`;

let index = [];
let grandTotal = 0;

for (const cat of spec.categories) {
  const n = cat.layers.length;
  grandTotal += n;

  const lines = [];
  lines.push(`<!-- GENERATED by art/build-prompt-packs.js — edit art/prompts.json instead -->`);
  lines.push(``);
  lines.push(`# ${cat.id} — ${cat.name}`);
  lines.push(``);
  lines.push(`**${n} layers** · z-order \`${cat.z}\` · ` +
    (cat.allowNone ? `\`none.png\` required (weight ${cat.noneWeight})` : `no None variant`));
  lines.push(``);
  lines.push(STYLE_REF);
  lines.push(``);
  lines.push(`## Batch note`);
  lines.push(``);
  lines.push(cat.batchNote);
  lines.push(``);
  lines.push(`## Output filenames`);
  lines.push(``);
  lines.push(`Save into \`generator/layers/${cat.id}/\` using these exact names — the \`#weight\``);
  lines.push(`suffix is what drives rarity, so do not drop it:`);
  lines.push(``);
  lines.push('```');
  for (const l of cat.layers) lines.push(`${l.file}#${l.weight}.png`);
  if (cat.allowNone) lines.push(`none#${cat.noneWeight}.png            <- npm run make-none creates this`);
  lines.push('```');
  lines.push(``);
  lines.push(`## Prompts`);
  lines.push(``);

  cat.layers.forEach((l, i) => {
    lines.push(`### ${i + 1}. ${l.name}  \`${l.file}\``);
    lines.push(`*${l.tier} · weight ${l.weight}*`);
    lines.push(``);
    lines.push('```text');
    lines.push(l.prompt);
    lines.push('```');
    lines.push(``);
  });

  lines.push(`---`);
  lines.push(``);
  lines.push(`## One-shot version`);
  lines.push(``);
  lines.push(`If your model handles long multi-image requests, paste this instead:`);
  lines.push(``);
  lines.push('```text');
  lines.push(`Generate ${n} separate images for the "${cat.name}" trait layer of my NFT collection.`);
  lines.push(`Apply the STYLE and OUTPUT RULES from my previous message to all of them.`);
  lines.push(``);
  lines.push(cat.batchNote);
  lines.push(``);
  cat.layers.forEach((l, i) => lines.push(`${i + 1}. [${l.file}] ${l.prompt}`));
  lines.push('```');
  lines.push(``);

  const file = path.join(outDir, `${cat.id}.md`);
  fs.writeFileSync(file, lines.join('\n'));
  index.push({ id: cat.id, name: cat.name, n, z: cat.z, none: cat.allowNone });
  console.log(`  wrote prompts/${cat.id}.md  (${n} layers)`);
}

// README index for the prompts folder
const readme = [
  `<!-- GENERATED by art/build-prompt-packs.js — edit art/prompts.json instead -->`,
  ``,
  `# Prompt Packs — ${spec.collection}`,
  ``,
  `**${grandTotal} layer assets across ${spec.categories.length} categories.**`,
  ``,
  `Work through these in order. Each file is one ChatGPT conversation.`,
  ``,
  `1. Open \`00-style.md\`, pick your concept, paste the style block into a new chat.`,
  `2. Run \`02-fur.md\` FIRST — you need the base body before anything else aligns.`,
  `3. Build \`../anchor-sheet.png\` from it, then work the rest in any order.`,
  ``,
  `| Pack | Layers | z | None? |`,
  `|---|---|---|---|`,
  ...index.map(c => `| [\`${c.id}\`](./${c.id}.md) ${c.name} | ${c.n} | ${c.z} | ${c.none ? 'yes' : 'no'} |`),
  `| **total** | **${grandTotal}** | | |`,
  ``,
].join('\n');

fs.writeFileSync(path.join(outDir, 'README.md'), readme);
console.log(`  wrote prompts/README.md`);

// Browser payload for lab.html. Written as a plain script assignment rather than
// fetched as JSON so the Lab page also works when opened directly from the filesystem.
const jsOut = path.join(ROOT, '..', 'assets', 'js', 'prompts-data.js');
fs.mkdirSync(path.dirname(jsOut), { recursive: true });
fs.writeFileSync(jsOut,
  `/* GENERATED by art/build-prompt-packs.js — edit art/prompts.json instead */\n` +
  `window.PROMPTS = ${JSON.stringify(spec)};\n`
);
console.log(`  wrote assets/js/prompts-data.js`);
console.log(`\n${grandTotal} layers across ${spec.categories.length} categories.`);
