#!/usr/bin/env node
/**
 * Regenerates everything derived from art/prompts.json:
 *
 *   node art/build-prompt-packs.js
 *
 *   → art/prompts/<category>.md        paste-ready batch files, one per category
 *   → art/prompts/README.md            index + totals
 *   → assets/js/prompts-data.js        the data the site and the Prompt Lab read
 *
 * prompts.json is the ONLY hand-edited source. Everything above is generated, so the
 * site, the docs and the art engine can never disagree about what the layers are.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const spec = JSON.parse(fs.readFileSync(path.join(__dirname, 'prompts.json'), 'utf8'));

const PROMPT_DIR = path.join(__dirname, 'prompts');
fs.mkdirSync(PROMPT_DIR, { recursive: true });

const total = spec.categories.reduce((n, c) => n + c.layers.length, 0);
if (total !== spec.totalLayers) {
  console.error(`\n  ✗ totalLayers says ${spec.totalLayers} but the categories hold ${total}.\n`);
  process.exit(1);
}

/* ── per-category batch files ─────────────────────────────────────────────── */
for (const cat of spec.categories) {
  const lines = [];
  lines.push(`# ${cat.name} — \`${cat.id}\``);
  lines.push('');
  lines.push(`**${cat.layers.length} layers**${cat.allowNone ? ` + a transparent \`none\` at weight ${cat.noneWeight}` : ''} · z-index ${cat.z}`);
  lines.push('');
  lines.push('> ' + cat.batchNote.replace(/\n/g, '\n> '));
  lines.push('');
  lines.push('| File | Name | Weight | Tier |');
  lines.push('|---|---|---:|---|');
  for (const l of cat.layers) {
    lines.push(`| \`${l.file}\` | ${l.name} | ${l.weight} | ${l.tier} |`);
  }
  lines.push('');
  lines.push('---');
  lines.push('');
  for (const l of cat.layers) {
    lines.push(`### ${l.name}  \`${l.file}#${l.weight}.png\``);
    lines.push('');
    lines.push('```');
    lines.push(l.prompt);
    lines.push('```');
    lines.push('');
  }
  fs.writeFileSync(path.join(PROMPT_DIR, `${cat.id}.md`), lines.join('\n'));
  console.log(`  art/prompts/${cat.id}.md`);
}

/* ── index ────────────────────────────────────────────────────────────────── */
const idx = [];
idx.push(`# ${spec.collection} — prompt packs`);
idx.push('');
idx.push(`Generated from \`art/prompts.json\`. Do not edit these by hand — edit the JSON and re-run`);
idx.push('`node art/build-prompt-packs.js`.');
idx.push('');
idx.push(`**${spec.totalLayers} layers** across ${spec.categories.length} categories, ${spec.canvas}×${spec.canvas} master.`);
idx.push('');
idx.push('| Category | Layers | None | z |');
idx.push('|---|---:|---|---:|');
for (const c of spec.categories) {
  idx.push(`| [${c.name}](${c.id}.md) | ${c.layers.length} | ${c.allowNone ? c.noneWeight : '—'} | ${c.z} |`);
}
idx.push(`| **Total** | **${spec.totalLayers}** | | |`);
idx.push('');
idx.push('## Anchors');
idx.push('');
idx.push('Every layer is drawn against these, in master-canvas pixels:');
idx.push('');
idx.push('| Anchor | Value |');
idx.push('|---|---:|');
for (const [k, v] of Object.entries(spec.anchors)) idx.push(`| \`${k}\` | ${v} |`);
idx.push('');
fs.writeFileSync(path.join(PROMPT_DIR, 'README.md'), idx.join('\n'));
console.log('  art/prompts/README.md');

/* ── site data ────────────────────────────────────────────────────────────── */
const banner = `/* GENERATED by art/build-prompt-packs.js from art/prompts.json — do not edit. */\n`;
fs.writeFileSync(
  path.join(ROOT, 'assets', 'js', 'prompts-data.js'),
  banner + 'window.PROMPTS = ' + JSON.stringify(spec) + ';\n'
);
console.log('  assets/js/prompts-data.js');
console.log(`\n  ${spec.totalLayers} layers across ${spec.categories.length} categories.\n`);
